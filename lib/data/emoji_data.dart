/// Offline emoji dataset with categories and keyword metadata for search.
///
/// Sourced from the Unicode/CLDR-derived `emojibase-data` keyword set so
/// the catalog spans the full modern emoji range (~1,900 entries across
/// 9 groups) instead of a small hand-picked subset - this is what makes
/// search results feel comparable to Gboard's own emoji picker instead
/// of "limited variety".
library;

class EmojiEntry {
  final String char;
  final List<String> keywords;
  const EmojiEntry(this.char, this.keywords);
}

class EmojiCategory {
  final String name;
  final String icon;
  final List<EmojiEntry> emojis;
  const EmojiCategory(this.name, this.icon, this.emojis);
}

/// A curated "Emoji Kitchen" style mash-up: two base emoji combined into
/// one expressive combo (see reference screenshot showing an "Emoji
/// Kitchen" strip above Recents). Google's real Emoji Kitchen renders a
/// single fused sticker image fetched from a network service; this
/// offline-first app instead inserts both glyphs together as a short,
/// expressive combo sequence (e.g. "😂❤️") - same one-tap "richer
/// reaction than a single emoji" idea, no network dependency.
class EmojiCombo {
  final String left;
  final String right;
  final List<String> keywords;
  const EmojiCombo(this.left, this.right, this.keywords);

  /// The text actually inserted when tapped.
  String get combined => '$left$right';
}

