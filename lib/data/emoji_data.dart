class EmojiSearch {
  static List<EmojiEntry> search(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return const [];
    final terms = q.split(RegExp(r'\s+'));
    final results = <EmojiEntry>[];
    for (final cat in kEmojiCategories) {
      for (final e in cat.emojis) {
        final hit = terms.every((t) => e.keywords.any((k) => k.contains(t)));
        if (hit) results.add(e);
      }
    }
    return results;
  }
}
